-- Coordenador de cada equipe (prefixo) segundo as planilhas históricas (Base POC 4.0 e POC - Jan a jul 2026),
-- usando o valor mais recente de "Coordenador da Equipe" por prefixo. Serve de apoio à Matriz de Responsabilidade
-- para equipes que não estão em pwa_equipes (que continua sendo a fonte principal e tem prioridade).
-- Tabela separada de pwa_equipes para não aparecer na lista de equipes do PWA.
create table if not exists public.equipes_coordenacao_historico (
  prefixo      text        primary key,   -- sempre em MAIÚSCULAS
  coordenador  text        not null,
  updated_at   timestamptz not null default now()
);

alter table public.equipes_coordenacao_historico enable row level security;

drop policy if exists equipes_coord_hist_select on public.equipes_coordenacao_historico;
create policy equipes_coord_hist_select on public.equipes_coordenacao_historico
  for select using (true);

drop policy if exists equipes_coord_hist_write on public.equipes_coordenacao_historico;
create policy equipes_coord_hist_write on public.equipes_coordenacao_historico
  for all to authenticated using (true) with check (true);

