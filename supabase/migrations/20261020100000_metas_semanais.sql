-- Metas semanais por pessoa (tabela que alimenta o BI): em cada semana de cada mês, quem entrava na lista de
-- observadores, a meta, o realizado e o "real" (realizado limitado à meta). Carregada da planilha "Metas POC".
-- Uma pessoa pode aparecer mais de uma vez na mesma semana (como na planilha); os totais somam todas as linhas.
create table if not exists public.metas_semanais (
  id         bigint generated by default as identity primary key,
  aba        text     not null check (aba in ('Operacional', 'Administrativo')),
  ano        smallint not null,
  mes        smallint not null check (mes between 1 and 12),
  semana     smallint not null check (semana between 1 and 4),
  matricula  text     not null,
  nome       text     not null,
  funcao     text,
  base       text,
  gerencia   text,
  gerente    text,
  processo   text,
  realizado  integer  not null default 0,
  meta       integer  not null default 0,
  real       integer  not null default 0
);

create index if not exists metas_semanais_periodo_idx on public.metas_semanais (ano, mes, aba, semana);

alter table public.metas_semanais enable row level security;

drop policy if exists "metas_semanais leitura" on public.metas_semanais;
create policy "metas_semanais leitura" on public.metas_semanais
  for select to anon, authenticated using (true);
